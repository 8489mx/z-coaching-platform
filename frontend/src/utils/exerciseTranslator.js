/**
 * Translates an exercise object or string into professional Arabic.
 * Checks existing name_ar, if it is in Arabic already it returns it;
 * otherwise it looks up the key in the comprehensive dictionary.
 */
export function getArabicExerciseName(ex) {
  if (!ex) return "تمرين عام";

  // If already an Arabic string with arabic characters
  const existingAr = typeof ex === 'object' ? (ex.name_ar || "") : "";
  if (existingAr && /[\u0600-\u06FF]/.test(existingAr)) {
    return existingAr;
  }

  // Extract raw key
  const rawKey = typeof ex === 'object' 
    ? (ex.exercise_code || ex.name_en || ex.name || "")
    : String(ex);

  const normalized = String(rawKey).toUpperCase().trim().replace(/[-\s]+/g, "_");
  if (EXERCISE_AR_MAP[normalized]) {
    return EXERCISE_AR_MAP[normalized];
  }

  // Check without trailing suffix
  const stripped = normalized.replace(/_MACHINE$/, "").replace(/S$/, "");
  if (EXERCISE_AR_MAP[stripped]) {
    return EXERCISE_AR_MAP[stripped];
  }

  return existingAr || rawKey;
}
