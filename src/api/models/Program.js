import { DataTypes } from "sequelize";
import sequelize from "../config/database.js";

const Program = sequelize.define("Program", {
  id: {
    type: DataTypes.INTEGER,
    autoIncrement: true,
    primaryKey: true,
  },
  user_id: {
    type: DataTypes.INTEGER,
    allowNull: false,
  },
  program_data: {
    type: DataTypes.JSON, // Stores the entire JSON generated by Master Engine
    allowNull: false,
  },
}, {
  tableName: "programs",
  timestamps: true,
});

export default Program;
