function createExerciseV2({
  exerciseCode,
  nameEn,
  nameAr,
  slotCode,
  primaryMuscle,
  secondaryMuscles = [],
  equipmentCode,
  minimumLoadCapacity = EquipmentLoadCapacity.LIGHT,
  beginnerFriendly = true,
  compound = true,
  prescriptionUnit = ExercisePrescriptionUnit.REPS,
}) {
  const isBodyweight = equipmentCode === EquipmentCode.BODYWEIGHT;
  const actualMinCapacity = isBodyweight ? EquipmentLoadCapacity.BODYWEIGHT_ONLY : minimumLoadCapacity;
  const allowedLocations = ALLOWED_LOCATIONS_BY_EQUIPMENT[equipmentCode] || Object.freeze([TrainingLocation.GYM]);

  return Object.freeze({
    exercise_code: exerciseCode,
    name_en: nameEn,
    name_ar: nameAr,
    slot_code: slotCode,
    primary_muscle: primaryMuscle,
    secondary_muscles: Object.freeze([...secondaryMuscles]),
    equipment_requirements: Object.freeze([
      Object.freeze({
        equipment_code: equipmentCode,
        minimum_load_capacity: actualMinCapacity,
      }),
    ]),
    allowed_locations: allowedLocations,
    beginner_friendly: beginnerFriendly,
    compound: compound,
    prescription_unit: prescriptionUnit,
  });
}

